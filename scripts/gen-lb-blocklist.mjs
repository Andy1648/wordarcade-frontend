// gen-lb-blocklist.mjs — writes supabase/migrations/002_blocked_terms.sql from the CLIENT's lists
// (src/moderation/blockedTerms.js ALL_TERMS + src/leaderboard/nameFilter.js ROOTS), so the DB name
// filter and the client one can never drift. Re-run after either list changes, then apply the SQL.
import { writeFileSync } from 'node:fs';
import { ALL_TERMS } from '../src/moderation/blockedTerms.js';
import { ROOTS } from '../src/leaderboard/nameFilter.js';

const exact = [...new Set(ALL_TERMS.map((t) => String(t).toLowerCase().replace(/[^a-z]/g, '')).filter(Boolean))].sort();
const q = (s) => `'${s.replace(/'/g, "''")}'`;
// A term that is also a ROOT is stored once, as a root (a root match is a superset of the exact one).
const kinds = new Map(exact.map((t) => [t, 'exact']));
for (const r of ROOTS) kinds.set(r, 'root');
const rows = [...kinds].map(([t, k]) => `(${q(t)}, '${k}')`);
const sql = `-- 002_blocked_terms.sql — GENERATED by scripts/gen-lb-blocklist.mjs. Do not edit by hand.
-- ${exact.length} exact terms (src/moderation/blockedTerms.js) + ${ROOTS.length} roots (src/leaderboard/nameFilter.js).
begin;
delete from private.blocked_terms;
insert into private.blocked_terms (term, kind) values
${rows.join(',\n')}
on conflict (term) do update set kind = excluded.kind;
commit;
`;
writeFileSync(new URL('../supabase/migrations/002_blocked_terms.sql', import.meta.url), sql);
console.log(`wrote ${exact.length} exact + ${ROOTS.length} roots`);
